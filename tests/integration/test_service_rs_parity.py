"""Extension-level compute-path parity (phase 5b): the frozen-seed
fixture generated by the REAL Python find_similar, replayed through
the compiled extension `cine_rec_engine._service_rs` — the true PyO3
boundary (one crossing, JSON in/out, GIL released for the stage).

cargo (crate-direct) runs the same fixture without the boundary; this
test is what proves the bridge itself is transparent.
"""

from __future__ import annotations

import asyncio
import json
import os
from pathlib import Path

import pytest

pytestmark = pytest.mark.integration

FIXTURE = (
    Path(__file__).resolve().parents[2]
    / "rust" / "service" / "tests" / "fixtures" / "service_parity.json"
)

ROW_KEYS = (
    "tmdb_id", "title", "title_en", "media_type", "rating", "genres",
    "poster_path", "collection_id", "release_year", "director_ids",
)


def _service_rs():
    try:
        from cine_rec_engine import _service_rs
    except ImportError as e:
        pytest.skip(f"_service_rs extension not built: {e}")
    return _service_rs


def _dsn():
    dsn = os.environ.get("CINE_REC_INTEGRATION_DSN", "")
    if not dsn:
        pytest.skip("needs CINE_REC_INTEGRATION_DSN")
    return dsn


@pytest.mark.parametrize("case_name", [
    c["name"] for c in json.loads(FIXTURE.read_text())["cases"]
])
def test_compute_matches_python(case_name):
    rs = _service_rs()
    dsn = _dsn()
    cases = {c["name"]: c for c in json.loads(FIXTURE.read_text())["cases"]}
    case = cases[case_name]

    out_json = asyncio.run(
        asyncio.to_thread(rs.compute, dsn, json.dumps(case["spec"]))
    )
    got = json.loads(out_json)

    want = case["results"]
    assert len(want) > 0, "n>0 rule"
    assert len(got["results"]) == len(want), (
        f"{case_name}: {len(got['results'])} vs {len(want)}"
    )
    assert abs(got["movie_ratio"] - case["movie_ratio"]) < 1e-12
    for i, (g, w) in enumerate(zip(got["results"], want)):
        for key in ROW_KEYS:
            assert g[key] == w[key], f"{case_name}[{i}].{key}"
        assert abs(g["score"] - w["score"]) <= 1e-9, (
            f"{case_name}[{i}].score {g['score']} vs {w['score']}"
        )


def test_extension_reports_itself():
    rs = _service_rs()
    assert rs.VERSION
    assert callable(rs.compute)


def test_recommend_full_live_vs_live():
    """The strongest parity claim: Python recommend_for_user vs the
    extension's recommend entry at the SAME instant on the SAME DB —
    no frozen fixture, so seed-recency drift cannot mask a bug."""
    rs = _service_rs()
    dsn = _dsn()
    import asyncio
    import asyncpg

    from cine_rec_engine import find_similar as fs

    async def _no_cache():
        return None

    fs._get_cache = _no_cache  # the documented parity deployment

    from cine_rec_engine import service as svc_mod
    from cine_rec_engine.config import EMBEDDING_COLUMN
    from cine_rec_engine.user_vector import load_user_vector

    async def run_both():
        pool = await asyncpg.create_pool(dsn, min_size=1, max_size=4)
        svc = svc_mod.RecommendationService()
        await svc.initialize(pool)
        try:
            py = await svc.recommend_for_user(910001, limit=30)
            uvec = await load_user_vector(pool, 910001, None)
            spec = {
                "user_id": 910001,
                "limit": 30,
                "explore": None,
                "emb_column": EMBEDDING_COLUMN,
                "knn_ft_enabled": True,
                "weights": {
                    "active": list(svc_mod.ACTIVE_WEIGHTS.values()),
                    "heuristic27": list(svc_mod.HEURISTIC_WEIGHTS_LIST),
                },
                "uvec": uvec,
            }
            return py, spec
        finally:
            await pool.close()

    py, spec = asyncio.run(run_both())
    got = json.loads(asyncio.run(asyncio.to_thread(
        rs.recommend, dsn, json.dumps(spec))))

    assert py["reason"] == "personalized"
    assert got["reason"] == py["reason"]
    assert got["vector_used"] == py["vector_used"]
    assert len(py["results"]) > 0, "n>0"
    assert len(got["results"]) == len(py["results"]), (
        f"{len(got['results'])} vs {len(py['results'])}"
    )
    # seeds: same selection at the same instant
    for g, w in zip(got["seeds"], py["seeds"]):
        assert g[0] == w[0] and g[1] == w[1]
        assert abs(g[2] - w[2]) < 1e-9
    for i, (g, w) in enumerate(zip(got["results"], py["results"])):
        assert g["tmdb_id"] == w["tmdb_id"], f"row {i}"
        for key in ("title", "media_type", "genres"):
            assert g[key] == w[key], f"row {i}.{key}"
        assert abs(g["score"] - w["score"]) <= 1e-9, f"row {i}.score"
